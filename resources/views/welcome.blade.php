    <script>
        // Initialize AOS
        AOS.init({
            duration: 800,
            once: true,
            offset: 50,
            disable: window.innerWidth < 640
        });

        // Initialize Lucide Icons
        lucide.createIcons();

        // Navbar Scroll Effect
        window.addEventListener('scroll', function() {
            const nav = document.getElementById('mainNav');
            if (window.scrollY > 50) {
                nav.classList.add('py-3', 'shadow-xl');
                nav.classList.remove('py-4');
            } else {
                nav.classList.remove('py-3', 'shadow-xl');
                nav.classList.add('py-4');
            }
        });

        // ============ MOBILE MENU TOGGLE - SIMPLE & WORKING ============
        const mobileMenuBtn = document.getElementById('mobileMenuBtn');
        const mobileNavLinks = document.getElementById('mobileNavLinks');
        const mobileMenuOverlay = document.getElementById('mobileMenuOverlay');
        let isMenuOpen = false;

        function toggleMobileMenu() {
            isMenuOpen = !isMenuOpen;
            
            if (isMenuOpen) {
                // Open menu
                mobileNavLinks.classList.add('active');
                mobileMenuOverlay.classList.add('active');
                document.body.style.overflow = 'hidden';
                
                // Change icon to X
                mobileMenuBtn.innerHTML = '<i data-lucide="x" class="w-5 h-5"></i>';
                lucide.createIcons();
            } else {
                // Close menu
                mobileNavLinks.classList.remove('active');
                mobileMenuOverlay.classList.remove('active');
                document.body.style.overflow = '';
                
                // Change icon back to menu
                mobileMenuBtn.innerHTML = '<i data-lucide="menu" class="w-5 h-5"></i>';
                lucide.createIcons();
            }
        }

        // Toggle menu when button clicked
        mobileMenuBtn.addEventListener('click', function(e) {
            e.preventDefault();
            e.stopPropagation();
            toggleMobileMenu();
        });

        // Close menu when clicking overlay
        mobileMenuOverlay.addEventListener('click', function(e) {
            e.preventDefault();
            e.stopPropagation();
            if (isMenuOpen) {
                toggleMobileMenu();
            }
        });

        // Close menu when clicking on a link in mobile menu
        const mobileLinks = mobileNavLinks.querySelectorAll('a');
        mobileLinks.forEach(link => {
            link.addEventListener('click', function(e) {
                // Only close menu if it's a hash link (not external)
                if (this.getAttribute('href').startsWith('#')) {
                    e.preventDefault();
                    if (isMenuOpen) {
                        toggleMobileMenu();
                    }
                    
                    // Smooth scroll to section
                    const targetId = this.getAttribute('href');
                    if (targetId !== '#') {
                        const targetElement = document.querySelector(targetId);
                        if (targetElement) {
                            window.scrollTo({
                                top: targetElement.offsetTop - 80,
                                behavior: 'smooth'
                            });
                        }
                    }
                }
            });
        });

        // Close menu when pressing ESC key
        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape' && isMenuOpen) {
                toggleMobileMenu();
            }
        });

        // Smooth scrolling for desktop anchor links
        document.querySelectorAll('a[href^="#"]').forEach(anchor => {
            anchor.addEventListener('click', function(e) {
                // Skip if it's mobile menu link (already handled above)
                if (this.closest('#mobileNavLinks')) return;
                
                e.preventDefault();
                
                const targetId = this.getAttribute('href');
                if (targetId === '#') return;
                
                const targetElement = document.querySelector(targetId);
                if (targetElement) {
                    window.scrollTo({
                        top: targetElement.offsetTop - 80,
                        behavior: 'smooth'
                    });
                }
            });
        });

        // Pause logo slider on hover
        const logoSliderTracks = document.querySelectorAll('.logo-slider-track');
        if (logoSliderTracks.length > 0) {
            logoSliderTracks.forEach(track => {
                track.addEventListener('mouseenter', () => {
                    track.style.animationPlayState = 'paused';
                });
                
                track.addEventListener('mouseleave', () => {
                    track.style.animationPlayState = 'running';
                });
                
                // Pause on touch for mobile
                track.addEventListener('touchstart', () => {
                    track.style.animationPlayState = 'paused';
                });
                
                track.addEventListener('touchend', () => {
                    setTimeout(() => {
                        track.style.animationPlayState = 'running';
                    }, 2000);
                });
            });
        }

        // Reinitialize AOS on window resize
        let resizeTimer;
        window.addEventListener('resize', () => {
            clearTimeout(resizeTimer);
            resizeTimer = setTimeout(() => {
                AOS.refresh();
            }, 250);
        });

        // Handle image loading errors
        document.addEventListener('DOMContentLoaded', function() {
            const images = document.querySelectorAll('img');
            images.forEach(img => {
                img.addEventListener('error', function() {
                    console.log('Image failed to load:', this.src);
                });
            });
        });

        // Fix untuk viewport di iOS
        function setViewportHeight() {
            let vh = window.innerHeight * 0.01;
            document.documentElement.style.setProperty('--vh', `${vh}px`);
        }
        
        setViewportHeight();
        window.addEventListener('resize', setViewportHeight);
        window.addEventListener('orientationchange', setViewportHeight);
    </script>
